"""Bar chart and one-page PDF report of the vehicle counts (matplotlib only)."""

from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from counting import VehicleCounter

LABELS = ["Cars enter", "Trucks enter", "Cars exit", "Trucks exit"]
COLORS = ["#1f4e9c", "#4fa3d9", "#b3263a", "#e8902a"]


def _values(counter: VehicleCounter) -> list[int]:
    return [counter.enter["car"], counter.enter["truck"], counter.exit["car"], counter.exit["truck"]]


def _draw_chart(ax, counter: VehicleCounter) -> None:
    values = _values(counter)
    bars = ax.bar(LABELS, values, color=COLORS)
    ax.bar_label(bars, padding=2)
    ax.set_ylabel("Vehicles")
    ax.set_title("Vehicle count summary")
    ax.set_ylim(0, max(values + [1]) * 1.2)
    ax.spines[["top", "right"]].set_visible(False)


def save_chart(counter: VehicleCounter, path: str | Path) -> Path:
    fig, ax = plt.subplots(figsize=(6, 4))
    _draw_chart(ax, counter)
    fig.tight_layout()
    fig.savefig(path, dpi=150)
    plt.close(fig)
    return Path(path)


def save_pdf(counter: VehicleCounter, path: str | Path, source_name: str = "") -> Path:
    fig = plt.figure(figsize=(8.27, 11.69))  # A4 portrait
    fig.text(0.5, 0.94, "Vehicle Counting Report", ha="center", fontsize=20, weight="bold")
    if source_name:
        fig.text(0.5, 0.915, f"Video: {source_name}", ha="center", fontsize=10, color="#555")
    lines = [
        f"Total vehicles entered: {counter.total_enter}",
        f"    Cars: {counter.enter['car']}    Trucks: {counter.enter['truck']}",
        "",
        f"Total vehicles exited: {counter.total_exit}",
        f"    Cars: {counter.exit['car']}    Trucks: {counter.exit['truck']}",
    ]
    for i, line in enumerate(lines):
        fig.text(0.12, 0.86 - i * 0.03, line, fontsize=13)
    ax = fig.add_axes([0.12, 0.25, 0.76, 0.38])
    _draw_chart(ax, counter)
    fig.text(0.5, 0.05, "Generated by YOLOv8 + ByteTrack vehicle counter", ha="center",
             fontsize=8, color="#888")
    fig.savefig(path)
    plt.close(fig)
    return Path(path)
